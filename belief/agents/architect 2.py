import logging
import re

from belief.agents.base import BaseAgent
from belief.config.models import ModelRole
from belief.llm import LLMClient
from belief.models.artifacts import FileManifest, FileManifestPlan
from belief.models.skeleton import (
    SkeletonArtifact,
    FileRole,
)
from belief.models.state import Phase, UnifiedState

logger = logging.getLogger("belief.agents.architect")

_MAX_FILES = {1: 4, 2: 6, 3: 12, 4: 20, 5: 30}

