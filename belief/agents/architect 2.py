"""Architect Agent — Skeleton Architecture (Milestone 1)

Outputs a SkeletonArtifact that captures the full typed interface layer:
- File tree with dependency edges
- Pydantic model chains with all fields typed
- Abstract base classes with method signatures
- Config schemas, exception hierarchies
- Skeleton vs implementation file split

Falls back to old FileManifestPlan if SkeletonArtifact parsing fails.
"""

from __future__ import annotations

