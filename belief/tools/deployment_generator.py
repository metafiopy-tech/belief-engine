def generate_dockerignore() -> str:
    """Generate .dockerignore."""
    return """# .dockerignore
__pycache__
*.pyc
.git
.gitignore
.env
.env.*
!.env.example
*.md
tests/
.pytest_cache/
.mypy_cache/
.venv/
venv/
"""


# ---------------------------------------------------------------------------
# All artifacts at once
# ---------------------------------------------------------------------------

def generate_all_deployment_artifacts(
    manifest: ProjectManifest,
) -> dict[str, str]:
    """
    Generate all deployment artifacts from a manifest.

    Returns dict of {filename: content}.
    """
    artifacts = {
        "Dockerfile": generate_dockerfile(manifest),
        "docker-compose.yml": generate_docker_compose(manifest),
        ".env.example": generate_env_example(manifest),
        "requirements.txt": generate_requirements_txt(manifest),
        ".dockerignore": generate_dockerignore(),
        ".github/workflows/ci.yml": generate_github_actions(manifest),
        "railway.toml": generate_railway_toml(manifest),
    }

    return artifacts
